-- ---------------------------------------------------------------------------
-- Order number generation (server-side only, format: RB-YYYYMMDD-00001)
-- ---------------------------------------------------------------------------

create table if not exists public.order_number_counters (
  counter_date date primary key,
  counter bigint not null default 0
);

create or replace function public.generate_order_number()
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_date text;
  v_counter bigint;
begin
  v_date := to_char(current_date, 'YYYYMMDD');

  insert into public.order_number_counters (counter_date, counter)
  values (current_date, 1)
  on conflict (counter_date)
  do update set counter = public.order_number_counters.counter + 1
  returning counter into v_counter;

  return 'RB-' || v_date || '-' || lpad(v_counter::text, 5, '0');
end;
$$;

revoke all on function public.generate_order_number() from public;
grant execute on function public.generate_order_number() to service_role;

-- ---------------------------------------------------------------------------
-- Extend orders table
-- ---------------------------------------------------------------------------

alter table public.orders
  add column if not exists order_number text,
  add column if not exists updated_at timestamptz not null default now();

-- Backfill order_number for existing rows (if any)
do $$
declare
  r record;
begin
  for r in
    select id from public.orders where order_number is null or order_number = ''
  loop
    update public.orders
    set order_number = public.generate_order_number()
    where id = r.id;
  end loop;
end;
$$;

create unique index if not exists idx_orders_order_number
  on public.orders (order_number);

