-- ---------------------------------------------------------------------------
-- Atomic stock deduction (prevents overselling race conditions)
-- ---------------------------------------------------------------------------

create or replace function public.deduct_product_stock(
  p_product_id bigint,
  p_quantity bigint
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_rows integer;
begin
  if p_quantity is null or p_quantity <= 0 then
    raise exception 'invalid_quantity';
  end if;

  update public.products
  set stock = stock - p_quantity
  where id = p_product_id
    and stock >= p_quantity;

  get diagnostics v_rows = row_count;
  return v_rows = 1;
end;
$$;

create or replace function public.fulfill_order_stock(p_order_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  item record;
  ok boolean;
begin
  for item in
    select product_id, sum(quantity)::bigint as total_qty
    from public.order_items
    where order_id = p_order_id
    group by product_id
  loop
    ok := public.deduct_product_stock(item.product_id, item.total_qty);
    if not ok then
      raise exception 'insufficient_stock:product_%', item.product_id;
    end if;
  end loop;
end;
$$;

create or replace function public.complete_order_payment(
  p_order_id uuid,
  p_zibal_ref_number text default null
)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_status text;
begin
  select status into v_status
  from public.orders
  where id = p_order_id
  for update;

  if not found then
    raise exception 'order_not_found';
  end if;

  if v_status = 'paid' then
    return 'already_paid';
  end if;

  perform public.fulfill_order_stock(p_order_id);

  update public.orders
  set
    status = 'paid',
    paid_at = now(),
    zibal_ref_number = coalesce(p_zibal_ref_number, zibal_ref_number),
    updated_at = now()
  where id = p_order_id;

  return 'paid';
end;
$$;

revoke all on function public.deduct_product_stock(bigint, bigint) from public;
revoke all on function public.fulfill_order_stock(uuid) from public;
revoke all on function public.complete_order_payment(uuid, text) from public;

grant execute on function public.deduct_product_stock(bigint, bigint) to service_role;
grant execute on function public.fulfill_order_stock(uuid) to service_role;
grant execute on function public.complete_order_payment(uuid, text) to service_role;

-- ---------------------------------------------------------------------------
-- Admin helper (Supabase Auth: app_metadata.role = 'admin')
-- ---------------------------------------------------------------------------

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(
    (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin'
    or (auth.jwt() -> 'user_metadata' ->> 'role') = 'admin',
    false
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;
grant execute on function public.is_admin() to anon;

