-- ---------------------------------------------------------------------------
-- Triggers: order_number on insert, updated_at on update
-- ---------------------------------------------------------------------------

create or replace function public.orders_before_insert()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.order_number is null or new.order_number = '' then
    new.order_number := public.generate_order_number();
  end if;
  new.updated_at := coalesce(new.updated_at, now());
  return new;
end;
$$;

drop trigger if exists trg_orders_before_insert on public.orders;
create trigger trg_orders_before_insert
  before insert on public.orders
  for each row
  execute function public.orders_before_insert();

create or replace function public.orders_before_update()
returns trigger
language plpgsql
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists trg_orders_before_update on public.orders;
create trigger trg_orders_before_update
  before update on public.orders
  for each row
  execute function public.orders_before_update();

